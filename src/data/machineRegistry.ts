export function getMachineById(id: string): MachineDefinition | undefined {
  return machineRegistry.find((m) => m.info.id === id);
}

export function getActiveMachineComponents(machineId: string): MachineComponent[] {
  return getMachineById(machineId)?.components ?? [];
}

export function getComponentFromMachine(machineId: string, componentId: string | null): MachineComponent | undefined {
  if (!componentId) return undefined;
  return getActiveMachineComponents(machineId).find((c) => c.id === componentId);
}
